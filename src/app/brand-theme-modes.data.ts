export type BrandThemeId = 'default' | 'silver' | 'gold' | 'diamond' | 'platinum' | 'premium';

export interface BrandThemeTab {
  id: BrandThemeId;
  label: string;
}

export interface BrandThemeTokenValue {
  primitive: string;
  value: string;
}

type BrandThemeValueMap = Record<BrandThemeId, BrandThemeTokenValue>;

export const DEFAULT_BRAND_THEME: BrandThemeId = 'default';

